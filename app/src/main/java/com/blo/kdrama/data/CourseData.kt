    val levels: List<Level> = listOf(beginner, elementary, preIntermediate, intermediate, advanced, pro)

    private val lessonIndex: Map<String, Pair<Level, Lesson>> =
        levels.flatMap { lvl -> lvl.lessons.map { it.id to (lvl to it) } }.toMap()

    fun level(id: String): Level? = levels.find { it.id == id }
    fun lesson(id: String): Lesson? = lessonIndex[id]?.second
    fun levelOf(lessonId: String): Level? = lessonIndex[lessonId]?.first
    val allLessons: List<Lesson> get() = levels.flatMap { it.lessons }
    val totalLessons: Int get() = allLessons.size
